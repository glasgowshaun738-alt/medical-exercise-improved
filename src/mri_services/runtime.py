# Application scaffolding
# --------------------------------------------------------------------------


def json_response(payload: dict[str, Any], status: int) -> Response:
    return Response(
        json.dumps(payload, sort_keys=True),
        status=status,
        mimetype="application/json",
    )


def create_app(service_name: str, logger: logging.Logger) -> Flask:
    """Build a Flask app with the bounds, error handling and probes in place.

    Both services get identical transport behaviour from here. Duplicating it
    would mean two error-handling paths that drift, and an orchestrator that
    has to special-case which service it is talking to.
    """
    app = Flask(service_name)

    # Refuse oversized bodies before reading them into memory. Werkzeug raises
    # RequestEntityTooLarge, translated below into the contract's error code so
    # that the orchestrator sees one error vocabulary rather than two.
    app.config["MAX_CONTENT_LENGTH"] = MAX_REQUEST_BYTES

    # Set once startup succeeds. `/health` answers "is the process alive",
    # `/ready` answers "can it serve a request". They are distinct because the
    # orchestrator has to tell a service that has not finished starting from
    # one that started and is broken -- and retry only the first.
    app.config["READY"] = False

    @app.errorhandler(ContractViolation)
    def _handle_contract_violation(exc: ContractViolation) -> Response:
        log_event(
            logger,
            "request_rejected",
            service=service_name,
            error=exc.code.value,
            field=exc.field,
            outcome="rejected",
        )
        return json_response(exc.as_payload(), 400)

    @app.errorhandler(RequestEntityTooLarge)
    def _handle_too_large(_exc: RequestEntityTooLarge) -> Response:
        violation = ContractViolation(
            ErrorCode.PAYLOAD_TOO_LARGE,
            "<body>",
            f"request exceeds {MAX_REQUEST_BYTES} bytes",
        )
        log_event(
            logger,
            "request_rejected",
            service=service_name,
            error=violation.code.value,
            outcome="rejected",
        )
        return json_response(violation.as_payload(), 413)

    @app.errorhandler(Exception)
    def _handle_unexpected(exc: Exception) -> Response:
        # Fail closed. Anything unanticipated becomes a refusal with a defined
        # code -- never a partial result, never a substituted default. The
        # detail is deliberately generic in the response and complete in the
        # log: an exception message can carry input-derived content, and the
        # response crosses a process boundary.
        if isinstance(exc, HTTPException):
            return json_response(
                {
                    "error": ErrorCode.SCHEMA_INVALID.value,
                    "field": "<request>",
                    "detail": exc.description,
                    "contract_version": CONTRACT_VERSION,
                },
                exc.code or 400,
            )
        logger.exception("unhandled error in %s", service_name)
        log_event(
            logger,
            "request_failed",
            service=service_name,
            error=ErrorCode.INTERNAL_ERROR.value,
            exception_type=type(exc).__name__,
            outcome="failed",
        )
        return json_response(
            {
                "error": ErrorCode.INTERNAL_ERROR.value,
                "field": "<service>",
                "detail": "internal error; see service log",
                "contract_version": CONTRACT_VERSION,
            },
            500,
        )

    @app.get("/health")
    def _health() -> Response:
        return json_response({"status": "alive", "service": service_name}, 200)

    @app.get("/ready")
    def _ready() -> Response:
        ready = bool(app.config["READY"])
        return json_response(
            {"status": "ready" if ready else "not_ready", "service": service_name},
            200 if ready else 503,
        )

    @app.get("/version")
    def _version() -> Response:
        # A regulated device must be able to state which software produced a
        # given clinical result. Three versions because they move
        # independently: the wire contract, the build, and the algorithm.
        return json_response(
            {
                "service": service_name,
                "contract_version": CONTRACT_VERSION,
                "software_version": SOFTWARE_VERSION,
                "algorithm_version": ALGORITHM_VERSION,
            },
            200,
        )

    return app


def read_json_body() -> Any:
    """Parse the request body as JSON, refusing anything that is not.

    `silent=True` because Flask's own 400 page is HTML, and the orchestrator
    branches on this service's error codes. A body that will not parse is a
    contract violation like any other.
    """
    body = request.get_json(silent=True)
    if body is None:
        raise ContractViolation(
            ErrorCode.SCHEMA_INVALID,
            "<body>",
            "request body must be JSON with Content-Type: application/json",
        )
    return body


def serve(app: Flask, logger: logging.Logger, service_name: str, port: int) -> None:
    """Run the service.

    Started by the platform's service manager, or by hand for this MVP -- never
    by the orchestrator. Nothing here assumes a parent process, so moving from
    three terminals to three service unit files changes no code. That is the
    point of the design, and it is what satisfies the requirement that these
    not be subprocesses of the orchestration code.

    `threaded=False` serialises requests. The device images one patient at a
    time, so concurrency here would buy nothing and would mean shared-state
    defects are possible where at present they are not.

    This is Flask's development server, which is appropriate for demonstrating
    the architecture and is not appropriate for the device. A production
    deployment needs a real WSGI server; that is a deployment change, not a
    change to anything above.
    """
    app.config["READY"] = True
    log_event(
        logger,
        "service_started",
        service=service_name,
        host=LOOPBACK_HOST,
        port=port,
    )
    app.run(host=LOOPBACK_HOST, port=port, threaded=False, debug=False)
